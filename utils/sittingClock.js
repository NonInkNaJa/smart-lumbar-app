// นาฬิกานับเวลานั่ง: นับตาม "เวลาจริง" ที่ผ่านไประหว่างการเรียกแต่ละครั้ง ไม่ใช่นับจำนวนครั้งที่ตัวจับเวลาเดิน
// เหตุผล: ตอนปิดจอ/อยู่เบื้องหลัง Android อาจหน่วงหรือข้ามรอบของ setInterval ถ้านับจำนวนรอบ เวลานั่งจะหายไป
export const MAX_TICK_GAP_MS = 6 * 60 * 60 * 1000; // ช่องว่างที่ยอมรับว่าเป็นเวลาจริงได้สูงสุดต่อครั้ง (เกินนี้ถือว่านาฬิกาเครื่องถูกปรับ)
export const NORMAL_TICK_MS = 1000; // ใช้แทนเมื่อพบว่านาฬิกาเครื่องกระโดดผิดปกติ (นับเท่ารอบปกติ 1 รอบ)

// เวลา (ms) ที่ควรนับเพิ่ม เมื่อเวลาเดินจาก last ไป now
//  - ปกติ/ตัวจับเวลาถูกหน่วง: นับเท่าที่ผ่านไปจริง
//  - นาฬิกาถอยหลัง (ผู้ใช้ปรับเวลาเครื่อง) หรือค่าผิดปกติ: นับ 0 (เวลานั่งไม่ถอยหลัง)
//  - นาฬิกากระโดดไปข้างหน้าเกิน MAX_TICK_GAP_MS: ไม่เชื่อ นับแค่ 1 รอบปกติ
export function elapsedSince(last, now) {
  const d = now - last;
  if (!Number.isFinite(d) || d <= 0) return 0;
  if (d > MAX_TICK_GAP_MS) return NORMAL_TICK_MS;
  return d;
}
